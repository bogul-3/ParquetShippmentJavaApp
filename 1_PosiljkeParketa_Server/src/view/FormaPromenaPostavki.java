    private void btnSacuvajPromeneActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSacuvajPromeneActionPerformed

        try {
            Integer.parseInt(txtServerSoket.getText());
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Morate uneti broj u polje serverSoket", "GRESKA", JOptionPane.ERROR_MESSAGE);
            return;
        }

        postavke.getProperties().setProperty("dbName", txtImeBaze.getText());
        postavke.getProperties().setProperty("user", txtUser.getText());
        postavke.getProperties().setProperty("pass", txtLozinka.getText());
        postavke.getProperties().setProperty("serverSoket", txtServerSoket.getText());

        postavke.sacuvaj();

        try {
            OutputStream out = new FileOutputStream("Postavke.properties");
            postavke.getProperties().store(out, null);
        } catch (FileNotFoundException ex) {
            Logger.getLogger(FormaPromenaPostavki.class.getName()).log(Level.SEVERE, null, ex);
        } catch (IOException ex) {
            Logger.getLogger(FormaPromenaPostavki.class.getName()).log(Level.SEVERE, null, ex);
        }

        this.dispose();
    }//GEN-LAST:event_btnSacuvajPromeneActionPerformed

    private void PostaviPostavke() {

        txtImeBaze.setText(postavke.getProperties().getProperty("dbName"));
        txtUser.setText(postavke.getProperties().getProperty("user"));
        txtLozinka.setText(postavke.getProperties().getProperty("pass"));
        txtServerSoket.setText(postavke.getProperties().getProperty("serverSoket"));
    }

